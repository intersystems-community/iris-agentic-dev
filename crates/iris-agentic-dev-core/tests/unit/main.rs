//! Aggregated unit-test target.
//!
//! These 99 files were 99 separate `[[test]]` targets. Cargo never runs test binaries in
//! parallel, so each one cost a process spawn: a warm run of the non-live suite spent ~170s of
//! its 254s starting processes rather than running tests, and a no-op build spent 44s just
//! walking the target list. As modules of one binary they spawn once and the in-binary tests run
//! on all cores.
//!
//! Add a file here and add its `mod` line below, or it will not run — the aggregator is the only
//! thing that pulls these in.

// Runs before `main`, so before any test thread: no test in this binary reaches the developer's
// real keychain or home directory. See `testing::isolate_process`.
#[ctor::ctor]
fn isolate_the_test_process() {
    iris_agentic_dev_core::testing::isolate_process();
    // The gate code reads the operator's `IRIS_*_ENABLED` variables once, on first use, and keeps
    // that snapshot for the life of the process. A unit test that asserts gate behaviour must not
    // depend on the shell that launched it (the CI e2e job exports both gates open), so the
    // snapshot is seeded with an empty operator environment before any test thread starts.
    iris_agentic_dev_core::tools::write_gate::init_operator_env_gates(Default::default());
}

