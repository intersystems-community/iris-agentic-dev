#!/usr/bin/env python3
"""Write the winget manifests for one iris-agentic-dev release (spec 152).

    python3 packaging/winget/winget_manifests.py --version 1.7.1 \
        --sha256 <hash of iris-agentic-dev-windows-x86_64.exe> --release-date 2026-11-01 --out DIR

writes DIR/manifests/i/InterSystemsCommunity/IrisAgenticDev/<version>/ with the three files
microsoft/winget-pkgs expects: version, defaultLocale (en-US) and installer. The Windows binary
is a single executable that loads only system DLLs, so it is a `portable` installer: winget
downloads it, checks the hash and puts `iris-agentic-dev` on PATH.

Standard library only, so it runs on a bare runner. The YAML is written by hand rather than
dumped, because every value here is known and a dumper would need a dependency.
"""

import argparse
import datetime
import os
import re
import sys

IDENTIFIER = "InterSystemsCommunity.IrisAgenticDev"
MANIFEST_VERSION = "1.10.0"
REPO = "https://github.com/intersystems-community/iris-agentic-dev"
ASSET = "iris-agentic-dev-windows-x86_64.exe"
COMMAND = "iris-agentic-dev"


def _license(repo_root):
    with open(os.path.join(repo_root, "Cargo.toml")) as f:
        m = re.search(r'^license\s*=\s*"([^"]+)"', f.read(), re.M)
    if not m:
        raise SystemExit("error: no license in Cargo.toml")
    return m.group(1)


def _manifest(kind, version, body):
    return (
        "# Generated by packaging/winget/winget_manifests.py; do not edit by hand.\n"
        f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.{MANIFEST_VERSION}.schema.json\n"
        "\n"
        f"PackageIdentifier: {IDENTIFIER}\n"
        f"PackageVersion: '{version}'\n"
        f"{body}"
        f"ManifestType: {kind}\n"
        f"ManifestVersion: {MANIFEST_VERSION}\n"
    )


def version_manifest(version):
    return _manifest("version", version, "DefaultLocale: en-US\n")


def locale_manifest(version, license_id):
    return _manifest(
        "defaultLocale",
        version,
        "PackageLocale: en-US\n"
        "Publisher: InterSystems Community\n"
        "PublisherUrl: https://github.com/intersystems-community\n"
        f"PublisherSupportUrl: {REPO}/issues\n"
        "Author: InterSystems Corporation\n"
        "PackageName: iris-agentic-dev\n"
        f"PackageUrl: {REPO}\n"
        f"License: {license_id}\n"
        f"LicenseUrl: {REPO}/blob/master/LICENSE\n"
        "Copyright: Copyright (c) 2025 InterSystems Corporation\n"
        "ShortDescription: MCP server that lets AI coding agents work against InterSystems IRIS.\n"
        "Description: |-\n"
        "  iris-agentic-dev is an MCP server and CLI for InterSystems IRIS. It gives an AI coding\n"
        "  agent tools to compile and run ObjectScript, query SQL and globals, run unit tests,\n"
        "  inspect interoperability productions and search the IRIS documentation, behind write,\n"
        "  destructive and per-server policy gates.\n"
        f"Moniker: {COMMAND}\n"
        "Tags:\n"
        "- intersystems\n"
        "- iris\n"
        "- objectscript\n"
        "- mcp\n"
        "- ai-agent\n"
        f"ReleaseNotesUrl: {REPO}/releases/tag/v{version}\n"
        "Documentations:\n"
        "- DocumentLabel: README\n"
        f"  DocumentUrl: {REPO}#readme\n",
    )


def installer_manifest(version, sha256, release_date):
    return _manifest(
        "installer",
        version,
        "InstallerType: portable\n"
        "Commands:\n"
        f"- {COMMAND}\n"
        f"ReleaseDate: '{release_date}'\n"
        "Installers:\n"
        "- Architecture: x64\n"
        f"  InstallerUrl: {REPO}/releases/download/v{version}/{ASSET}\n"
        f"  InstallerSha256: {sha256.upper()}\n",
    )


def _check(args):
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", args.version):
        raise SystemExit(f"error: --version must be X.Y.Z, got {args.version!r}")
    if not re.fullmatch(r"[0-9a-fA-F]{64}", args.sha256):
        raise SystemExit(
            f"error: --sha256 must be 64 hex characters, got {args.sha256!r}"
        )
    try:
        datetime.date.fromisoformat(args.release_date)
    except ValueError:
        raise SystemExit(
            f"error: --release-date must be YYYY-MM-DD, got {args.release_date!r}"
        )


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument(
        "--version", required=True, help="release version, X.Y.Z (no leading v)"
    )
    p.add_argument("--sha256", required=True, help=f"SHA-256 of {ASSET}")
    p.add_argument("--release-date", required=True, help="YYYY-MM-DD")
    p.add_argument(
        "--out", required=True, help="directory that receives manifests/i/..."
    )
    args = p.parse_args(argv)
    _check(args)

    repo_root = os.path.dirname(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    )
    publisher, name = IDENTIFIER.split(".")
    pkg_dir = os.path.join(
        args.out, "manifests", publisher[0].lower(), publisher, name, args.version
    )
    os.makedirs(pkg_dir, exist_ok=True)

    files = {
        f"{IDENTIFIER}.yaml": version_manifest(args.version),
        f"{IDENTIFIER}.locale.en-US.yaml": locale_manifest(
            args.version, _license(repo_root)
        ),
        f"{IDENTIFIER}.installer.yaml": installer_manifest(
            args.version, args.sha256, args.release_date
        ),
    }
    for fname, text in files.items():
        with open(os.path.join(pkg_dir, fname), "w", newline="\n") as f:
            f.write(text)
    print(pkg_dir)


if __name__ == "__main__":
    sys.exit(main())
